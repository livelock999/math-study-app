def build_questions():
    questions = []
    for identifier, text, prompt, choices, answer, kind, difficulty, hint, number, interpretation in _MATERIALS:
        evidence = text.split("\n")[number - 1]
        tags = ["sentence_understanding", "context", kind]
        tags.append("connection" if kind == "reason" else "inference")
        if kind == "reason" and difficulty > 1:
            tags.append("inference")
        questions.append({
            "question_id": identifier, "category": "passage", "problem_format": "choice",
            "text": text, "question": prompt, "choices": list(choices), "answer": answer,
            "skill_tags": tags,
            "question_word": "why" if kind == "reason" else "how",
            "reasoning_level": 2 if difficulty == 1 else 3 if difficulty == 2 else 4,
            "difficulty": difficulty, "hint": hint,
            "explanation": f"てがかりは {number}ぶんめの『{evidence}』\n{interpretation}\nこたえは「{choices[answer]}」だよ。",
            "error_tags": {str(index): ["context", "find_answer" if difficulty == 1 else "inference"]
                           for index in range(3) if index != answer},
            "version": 1,
        })
    return questions


QUESTIONS = build_questions()
